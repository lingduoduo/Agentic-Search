"""Stub package for the generated OpenAPI client.

The real client is generated by openapi-generator:
  openapi-generator generate -i backend/generated/openapi.json -g python \
    -o generated/agentic_search_openapi_client \
    --package-name agentic_search_openapi_client

Until then this stub lets tests that import the client be collected without errors.
Tests that actually exercise the client will fail at runtime when the live server
is not available — that is expected for local development without a running server.
"""

from types import ModuleType as _ModuleType
import sys as _sys


class Configuration:
    def __init__(self, host: str = "http://localhost:8080") -> None:
        self.host = host


class ApiClient:
    def __init__(self, configuration: Configuration | None = None) -> None:
        self.configuration = configuration or Configuration()

    def __enter__(self):
        return self

    def __exit__(self, *args):
        pass


class ApiException(Exception):
    def __init__(self, status: int = 0, reason: str = "") -> None:
        self.status = status
        self.reason = reason
        super().__init__(f"({status}) {reason}")
